"""LLM-as-judge metrics for semantic quality evaluation.

Each judge function sends a compact representation of one artifact to an LLM
and asks for a 1-10 score with structured reasoning.  Content is truncated
before sending so token usage stays predictable.
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from typing import Any

from antcrew.core.agent import _strip_fences
from antcrew.models.base import BaseLLM


# ---------------------------------------------------------------------------
# Result model
# ---------------------------------------------------------------------------

@dataclass
class JudgeResult:
    """Qualitative score from an LLM judge (0.0 – 1.0)."""

    artifact: str          # "prd" | "tickets" | "code" | "tests" | "review"
    score: float           # 0.0 – 1.0 (normalised from 1-10)
    raw_score: int         # original 1-10 score
    reasoning: str
    strengths: list[str] = field(default_factory=list)
    weaknesses: list[str] = field(default_factory=list)

    def to_dict(self) -> dict:
        return {
            "artifact":   self.artifact,
            "score":      round(self.score, 2),
            "raw_score":  self.raw_score,
            "reasoning":  self.reasoning,
            "strengths":  self.strengths,
            "weaknesses": self.weaknesses,
        }


# ---------------------------------------------------------------------------
# Shared helpers
# ---------------------------------------------------------------------------

_RESPONSE_FORMAT = """\

Respond ONLY with a valid JSON object (no markdown fences, no prose):
{"score": <integer 1-10>, "reasoning": "<2-3 sentences>", \
"strengths": ["...", "..."], "weaknesses": ["...", "..."]}
"""


def _truncate(text: str, max_chars: int = 2_000) -> str:
    if len(text) <= max_chars:
        return text
    return text[:max_chars] + f"\n... [{len(text) - max_chars} chars truncated]"


def _parse(artifact: str, raw: str) -> JudgeResult:
    try:
        data = json.loads(_strip_fences(raw))
        raw_score = max(1, min(10, int(data.get("score", 5))))
        return JudgeResult(
            artifact=artifact,
            score=round(raw_score / 10, 2),
            raw_score=raw_score,
            reasoning=str(data.get("reasoning", "")),
            strengths=list(data.get("strengths") or []),
            weaknesses=list(data.get("weaknesses") or []),
        )
    except Exception as exc:
        return JudgeResult(
            artifact=artifact,
            score=0.5,
            raw_score=5,
            reasoning=f"[Judge parse error: {exc}] {raw[:200]}",
            weaknesses=["Could not parse judge response"],
        )


def _absent(artifact: str, reason: str = "No output produced") -> JudgeResult:
    return JudgeResult(
        artifact=artifact, score=0.0, raw_score=0,
        reasoning=reason, weaknesses=[reason],
    )


# ---------------------------------------------------------------------------
# Judge functions — one per artifact type
# ---------------------------------------------------------------------------

_PRD_SYSTEM = """\
You are evaluating a Product Requirements Document (PRD) generated by an AI.
Score it 1–10 on: relevance to the original request, completeness of \
functional requirements, and clarity / specificity of goals.\
""" + _RESPONSE_FORMAT


def judge_prd(prd: Any, request: str, llm: BaseLLM) -> JudgeResult:
    """Score a PRD for relevance, completeness, and clarity."""
    if prd is None:
        return _absent("prd")
    try:
        prd_text = prd.model_dump_json(indent=2)
    except Exception:
        prd_text = str(prd)
    user = f"Original request:\n{request}\n\nGenerated PRD:\n{_truncate(prd_text, 2_500)}"
    return _parse("prd", llm.system(_PRD_SYSTEM, user))


_TICKETS_SYSTEM = """\
You are evaluating development tickets generated by an AI PM from a PRD.
Score them 1–10 on: coverage of PRD requirements, implementability of each \
ticket, and quality of acceptance criteria.\
""" + _RESPONSE_FORMAT


def judge_tickets(tickets: Any, prd: Any, llm: BaseLLM) -> JudgeResult:
    """Score tickets for coverage, implementability, and criteria quality."""
    if not tickets:
        return _absent("tickets")

    prd_ctx = ""
    if prd:
        title   = getattr(prd, "title", "") or ""
        summary = getattr(prd, "summary", "") or ""
        goals   = getattr(prd, "goals", []) or []
        prd_ctx = f"PRD: {title}\n{summary}\nGoals: {', '.join(str(g) for g in goals[:5])}\n\n"

    rows = "\n".join(
        f"- [{getattr(t, 'id', '?')}] {getattr(t, 'title', '?')}: "
        f"{', '.join(str(c) for c in (getattr(t, 'acceptance_criteria', []) or [])[:2])}"
        for t in list(tickets)[:12]
    )
    user = f"{prd_ctx}Tickets:\n{rows}"
    return _parse("tickets", llm.system(_TICKETS_SYSTEM, user))


_CODE_SYSTEM = """\
You are a senior engineer evaluating AI-generated code artifacts.
Score them 1–10 on: completeness (all tickets implemented?), correctness \
(logic is sound, no obvious bugs), and code quality (idiomatic, readable).\
""" + _RESPONSE_FORMAT


def judge_code(code_artifacts: Any, tickets: Any, llm: BaseLLM) -> JudgeResult:
    """Score code artifacts for completeness, correctness, and quality."""
    if not code_artifacts:
        return _absent("code")

    ticket_titles = "\n".join(
        f"- {getattr(t, 'title', '?')}" for t in (list(tickets)[:6] if tickets else [])
    ) or "(no tickets)"

    code_blocks = "\n\n".join(
        f"### {getattr(a, 'file_path', '?')}\n"
        f"{getattr(a, 'description', '')}\n"
        f"```\n{_truncate(getattr(a, 'content', ''), 300)}\n```"
        for a in list(code_artifacts)[:5]
    )
    user = _truncate(f"Tickets to implement:\n{ticket_titles}\n\nCode:\n{code_blocks}", 4_000)
    return _parse("code", llm.system(_CODE_SYSTEM, user))


_TESTS_SYSTEM = """\
You are a senior QA engineer evaluating an AI-generated test suite.
Score it 1–10 on: coverage of functionality and edge cases, correctness of \
assertions, and completeness relative to the code artifacts.\
""" + _RESPONSE_FORMAT


def judge_tests(test_artifacts: Any, code_artifacts: Any, llm: BaseLLM) -> JudgeResult:
    """Score tests for coverage, assertion correctness, and completeness."""
    if not test_artifacts:
        return _absent("tests")

    code_files = ", ".join(
        getattr(a, "file_path", "?") for a in (list(code_artifacts)[:5] if code_artifacts else [])
    ) or "(none)"

    test_blocks = "\n\n".join(
        f"### {getattr(t, 'file_path', '?')}"
        f" [{', '.join(getattr(t, 'coverage_areas', []) or [])}]\n"
        f"```\n{_truncate(getattr(t, 'content', ''), 300)}\n```"
        for t in list(test_artifacts)[:4]
    )
    user = f"Code files: {code_files}\n\nTests:\n{test_blocks}"
    return _parse("tests", llm.system(_TESTS_SYSTEM, user))


_REVIEW_SYSTEM = """\
You are a tech lead evaluating an AI-generated code review.
Score it 1–10 on: accuracy of findings (valid, non-trivial issues), \
actionability (specific, fixable suggestions), and balance \
(acknowledges positives alongside negatives).\
""" + _RESPONSE_FORMAT


def judge_review(review: Any, llm: BaseLLM) -> JudgeResult:
    """Score a code review for accuracy, actionability, and balance."""
    if review is None:
        return _absent("review")

    verdict  = getattr(review, "verdict", "") or ""
    summary  = getattr(review, "summary", "") or ""
    findings = list(getattr(review, "findings", []) or [])

    rows = "\n".join(
        f"- [{getattr(f, 'severity', '?')}] {getattr(f, 'file_path', '?')}: "
        f"{getattr(f, 'message', '')} → {getattr(f, 'suggestion', None) or 'no suggestion'}"
        for f in findings[:10]
    )
    user = f"Verdict: {verdict}\nSummary: {summary}\nFindings ({len(findings)} total):\n{rows}"
    return _parse("review", llm.system(_REVIEW_SYSTEM, user))
